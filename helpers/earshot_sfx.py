#!/usr/bin/env python3
"""earshot_sfx.py: foley made by earshot, straight into the Prisma SFX library.

  python helpers/earshot_sfx.py make "porta de carro batendo" [--name porta] [--takes 3]
  python helpers/earshot_sfx.py kit carro          # the car foley set, once
  python helpers/earshot_sfx.py status

earshot (MIT, github.com/Leonxlnx/earshot) renders sound effects from a request in words, on the
CPU, with no audio files and no network; every sound is free to use. Measured 2026-11-22 against
the Prisma libraries (`sfx_index.py`, phone speaker): it ADDS car foley the Prisma did not have
(door, engine start, pass-by, tyre screech, lock, shutter — all "toca bem" on a phone); for
transitions (whoosh, impact, riser, ping) the Prisma kit already covers it. It has no revving
sports engine: a request it can only approximate is reported as a "palpite".

Where things are (all outside the repository):
  earshot binary   $PRISMA_EARSHOT (a command), else ~/.prisma/earshot/Scripts/earshot.exe
                   (Windows) or ~/.prisma/earshot/bin/earshot, else `earshot` on PATH
  library          $PRISMA_SFX_EARSHOT, else ~/.prisma/sfx/earshot — read by sfx_index.py
Install (once, ~350 MB, CPU only):
  python -m venv ~/.prisma/earshot
  ~/.prisma/earshot/Scripts/python -m pip install "earshot @ git+https://github.com/Leonxlnx/earshot"
Every file made is recorded in media_ledger.py (source earshot, licence MIT / generated by code).
"""
from __future__ import annotations

import argparse
import os
import re
import shlex
import shutil
import subprocess
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
sys.path.insert(0, str(HERE))

INSTALL_HINT = ("earshot não encontrado. Instale uma vez (~350 MB, só CPU):\n"
                "  python -m venv ~/.prisma/earshot\n"
                '  ~/.prisma/earshot/Scripts/python -m pip install "earshot @ git+https://github.com/Leonxlnx/earshot"\n'
                "ou aponte PRISMA_EARSHOT para o comando.")

# The car foley set: (file name, request in words). Requests in English: earshot's catalogue is.
KITS = {
    "carro": [
        ("porta_carro", "a car door closing"),
        ("carro_partida", "a car engine starting"),
        ("carro_passando", "a car passing by fast"),
        ("pneu_cantando", "tires screeching"),
        ("chave_fechadura", "a car key lock click"),
        ("camera_obturador", "a camera shutter click"),
    ],
}


def earshot_cmd() -> list[str]:
    env = os.environ.get("PRISMA_EARSHOT", "").strip()
    if env:
        cmd = shlex.split(env, posix=False)
        cmd = [c.strip('"') for c in cmd]
        if not Path(cmd[0]).exists() and shutil.which(cmd[0]) is None:
            sys.exit(INSTALL_HINT)
        return cmd
    home = Path.home() / ".prisma" / "earshot"
    for c in (home / "Scripts" / "earshot.exe", home / "bin" / "earshot"):
        if c.exists():
            return [str(c)]
    w = shutil.which("earshot")
    if w:
        return [w]
    sys.exit(INSTALL_HINT)


def library() -> Path:
    import sfx_index
    return sfx_index.earshot_dir()


def make(request: str, name: str | None = None, takes: int = 1) -> list[Path]:
    lib = library()
    lib.mkdir(parents=True, exist_ok=True)
    base = name or re.sub(r"[^a-z0-9]+", "_", request.lower()).strip("_")[:40]
    out = lib / f"{base}.wav"
    cmd = earshot_cmd() + ["make", (f"{takes} variations of " if takes > 1 else "") + request, "-o", str(out)]
    p = subprocess.run(cmd, capture_output=True, text=True, encoding="utf-8", errors="replace")
    if p.returncode != 0:
        sys.exit(f"earshot falhou: {(p.stderr or p.stdout)[-600:]}")
    made = sorted(lib.glob(f"{base}*.wav"))
    first = (p.stdout.strip().splitlines() or [""])[0]
    print(f"  + {base}: {first.split(':', 1)[-1].strip()}")
    if "is a guess" in p.stdout or "is only the nearest" in p.stdout:
        print("    palpite: o earshot não tem exatamente esse som; ouça antes de usar")
    import media_ledger
    for f in made:
        media_ledger.record(f, "earshot", request, "MIT (gerado por código, uso livre)", "earshot / Leonxlnx",
                            "https://github.com/Leonxlnx/earshot", None)
    return made


def main() -> int:
    if hasattr(sys.stdout, "reconfigure"):
        sys.stdout.reconfigure(encoding="utf-8", errors="replace")
    ap = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    sub = ap.add_subparsers(dest="cmd", required=True)
    mk = sub.add_parser("make")
    mk.add_argument("request")
    mk.add_argument("--name")
    mk.add_argument("--takes", type=int, default=1)
    kt = sub.add_parser("kit")
    kt.add_argument("kit", choices=sorted(KITS))
    sub.add_parser("status")
    a = ap.parse_args()
    if a.cmd == "make":
        make(a.request, a.name, a.takes)
    elif a.cmd == "kit":
        for name, req in KITS[a.kit]:
            make(req, name)
    else:
        lib = library()
        try:
            cmd = earshot_cmd()
            print(f"  earshot: {' '.join(cmd)}")
        except SystemExit as e:
            print(f"  earshot: não instalado\n{e}")
        n = len(list(lib.glob("*.wav"))) if lib.exists() else 0
        print(f"  biblioteca: {lib} ({n} sons)")
        return 0
    print(f"  biblioteca: {library()} — atualize o índice com `sfx_index.py build`")
    return 0


if __name__ == "__main__":
    sys.exit(main())
