#!/usr/bin/env python3
"""Install the Prisma agents into every runtime from one source.

  python agents/sync_agents.py [--claude-dir D] [--vault-dir D] [--check]

Source (this repository):
  agents/claude/<id>.md   the Claude Code agent (frontmatter + instructions)
  agents/agents.json      the vault definition fields (mission, inputs, outputs, authority, gates)

Writes:
  <claude-dir>/<id>.md                 default ~/.claude/agents (only if ~/.claude exists)
  <vault-dir>/<id>/agent.yaml          default ~/.aiox-global/agents (only if it exists) — read by the
                                       Maestro, Hermes and Lissa, which do not load ~/.claude/agents
--check  writes nothing; exit 1 when an installed copy differs from the source.
"""
from __future__ import annotations

import argparse
import json
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
SOURCE_MD = HERE / "claude"
REGISTRY = HERE / "agents.json"


def _y(v, ind: int = 0) -> str:
    """Tiny YAML emitter for the registry's shapes (str, bool, list[str], dict[str, bool])."""
    pad = " " * ind
    if isinstance(v, bool):
        return "true" if v else "false"
    if isinstance(v, str):
        return json.dumps(v, ensure_ascii=False)
    if isinstance(v, list):
        return "\n" + "\n".join(f"{pad}  - {_y(x)}" for x in v)
    if isinstance(v, dict):
        return "\n" + "\n".join(f"{pad}  {k}: {_y(x, ind + 2)}" for k, x in v.items())
    return str(v)


def vault_yaml(a: dict, md_path: Path) -> str:
    keys = ("id", "name", "type", "reports_to", "mission", "authority", "inputs", "outputs", "skills", "gates",
            "when", "tool_profile")
    lines = ["# Generated by Prisma agents/sync_agents.py — edit the source in the Prisma repo, not here."]
    lines += [f"{k}: {_y(a[k])}" for k in keys if k in a]
    lines.append(f"instructions: {_y(str(md_path))}")
    lines.append('runtime_note: "Claude Code loads it as a subagent; other runtimes (Lissa, Codex) read the instructions file and follow it inline."')
    return "\n".join(lines) + "\n"


def plan(claude_dir: Path | None, vault_dir: Path | None) -> list[tuple[Path, str]]:
    reg = json.loads(REGISTRY.read_text(encoding="utf-8"))["agents"]
    out: list[tuple[Path, str]] = []
    for a in reg:
        src = SOURCE_MD / f"{a['id']}.md"
        md = src.read_text(encoding="utf-8")
        if claude_dir is not None:
            out.append((claude_dir / f"{a['id']}.md", md))
        if vault_dir is not None:
            installed_md = (claude_dir / f"{a['id']}.md") if claude_dir is not None else src
            out.append((vault_dir / a["id"] / "agent.yaml", vault_yaml(a, installed_md)))
    return out


def main() -> int:
    if hasattr(sys.stdout, "reconfigure"):
        sys.stdout.reconfigure(encoding="utf-8", errors="replace")
    ap = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    ap.add_argument("--claude-dir", type=Path)
    ap.add_argument("--vault-dir", type=Path)
    ap.add_argument("--check", action="store_true")
    a = ap.parse_args()
    home = Path.home()
    claude = a.claude_dir or ((home / ".claude" / "agents") if (home / ".claude").exists() else None)
    vault = a.vault_dir or ((home / ".aiox-global" / "agents") if (home / ".aiox-global" / "agents").exists() else None)
    diff = 0
    for path, text in plan(claude, vault):
        cur = path.read_text(encoding="utf-8") if path.exists() else None
        if cur == text:
            print(f"  = {path}")
            continue
        diff += 1
        if a.check:
            print(f"  ≠ {path}")
            continue
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(text, encoding="utf-8")
        print(f"  + {path}")
    if claude is None and vault is None:
        print("  nada a instalar: nem ~/.claude nem ~/.aiox-global/agents existem")
    return 1 if (a.check and diff) else 0


if __name__ == "__main__":
    sys.exit(main())
